"""Hand-authored gold backbone -> Diamond.

Diamond is the HUMAN-VERIFIED hand-authored `gold/*.jsonl` backbone: one file per axis, every
line double-checked by >=2 annotators + adjudication and flagged `diamond:true` for the
hardest. Procedural samples NEVER enter Diamond — they are generated by
`spar.dataset.generator.generate`, which this module never calls. The `gold_replay ~= 1.0`
gate runs against this backbone.

The hand-authored gold uses per-axis ids (`spar_<axis>_<label>`), NOT a `spar_gold_` prefix.
The non-collision invariant is enforced by SOURCE (this reads `load_gold` files; procedural
ids come only from `GenSpec.sample_id`, which carries a difficulty segment that hand-authored
ids never have) rather than by a synthetic id prefix — so no existing gold file is renamed.
"""

from __future__ import annotations

from spar.dataset.loader import load_gold
from spar.simulator.enums import Axis, Difficulty
from spar.simulator.schemas import Sample

# Every axis with a hand-authored backbone file. `load_gold` returns [] for an absent file.
GOLD_AXES: tuple[str, ...] = tuple(a.value for a in Axis)

# A procedural id (GenSpec.sample_id) always carries a difficulty segment; hand-authored
# gold ids never do — this is the hand-authored-vs-procedural discriminator.
_DIFFICULTY_SEGMENTS: frozenset[str] = frozenset(d.value for d in Difficulty)


def is_hand_authored_id(sample_id: str) -> bool:
    """True iff `sample_id` is NOT procedural-shaped (no difficulty segment)."""
    return not (set(sample_id.split("_")) & _DIFFICULTY_SEGMENTS)


def load_gold_backbone() -> list[Sample]:
    """Every hand-authored gold sample across all axes with a backbone file."""
    backbone: list[Sample] = []
    for axis in GOLD_AXES:
        backbone.extend(load_gold(axis))
    return sorted(backbone, key=lambda s: s.sample_id)


def diamond_backbone() -> list[Sample]:
    """The Diamond split source: the `diamond:true` subset of the hand-authored backbone.
    Procedural samples are excluded by construction (they are never loaded here)."""
    return [s for s in load_gold_backbone() if s.diamond]
